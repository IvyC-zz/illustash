"""生成 packaging/rust-licenses/：每个第三方 Rust crate 的许可文本（#161）。

对构建发布程序所用 lock 文件所在的三个 workspace 运行 cargo-about（版本固定见下，离线），写出
rust-dependencies.txt（作为 resources/licenses/ 随包发布）和 crates.json（它覆盖了哪些 crate，由 packaging/build.py
与 lock 文件核对）。任何 Cargo.lock 或依赖 feature 改动之后都要重新运行；crate 源码必须已在本地 cargo registry 里
（`cargo fetch --manifest-path ...`）：

    cargo install --locked --features cli cargo-about@0.9.2
    python3 tools/gen_rust_licenses.py [--cargo-about PATH]
"""
import argparse
import hashlib
import importlib.util
import json
from pathlib import Path
import subprocess
import sys
import tempfile
import textwrap

ROOT = Path(__file__).resolve().parents[1]
CARGO_ABOUT = 'cargo-about 0.9.2'
OUT = ROOT / 'packaging/rust-licenses'

spec = importlib.util.spec_from_file_location('build', ROOT / 'packaging/build.py')
build = importlib.util.module_from_spec(spec)
spec.loader.exec_module(build)


def lf(text):
    # 仓库按 LF 检出文本（.gitattributes）；写出的内容要和将提交的完全一致。
    return text.replace('\r\n', '\n').replace('\r', '\n')


def about(executable, workspace, scratch):
    output = scratch / (workspace.replace('/', '_') + '.json')
    subprocess.run([executable, 'generate', '--format', 'json', '--frozen', '--all-features', '--fail',
                    '--config', str(OUT / 'about.toml'), '--manifest-path', str(ROOT / workspace / 'Cargo.toml'),
                    '--output-file', str(output)], check=True, cwd=ROOT)
    return json.loads(output.read_text(encoding='utf-8'))


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--cargo-about', default='cargo-about', help='cargo-about executable')
    args = parser.parse_args()
    version = subprocess.run([args.cargo_about, '--version'], check=True, capture_output=True, text=True).stdout.strip()
    if version != CARGO_ABOUT:
        sys.exit(f'{CARGO_ABOUT} required, found {version!r}: cargo install --locked --features cli {CARGO_ABOUT.replace(" ", "@")}')
    declared, texts, workspaces = {}, {}, {}
    with tempfile.TemporaryDirectory(prefix='illustash-rust-licenses-') as scratch:
        for workspace in build.RUST_WORKSPACES:
            result = about(args.cargo_about, workspace, Path(scratch))
            for krate in result['crates']:
                declared[f"{krate['package']['name']} {krate['package']['version']}"] = krate['license']
            covered = set()
            for license in result['licenses']:
                users = {f"{use['crate']['name']} {use['crate']['version']}" for use in license['used_by']}
                texts.setdefault((license['id'], license['name'], lf(license['text'])), set()).update(users)
                covered |= users
            locked = build.third_party_crates(ROOT / workspace / 'Cargo.lock')
            if covered - locked:
                sys.exit(f'{workspace}: cargo-about reported crates absent from Cargo.lock: {sorted(covered - locked)}')
            # lock 文件里的可选依赖，若没有任何 workspace 成员的 feature 启用它，就从不编译。
            workspaces[workspace] = {'crates': sorted(covered), 'not_built': sorted(locked - covered)}
    def key(name):
        crate, version = name.split(' ')
        return crate.lower(), [(0, int(part), '') if part.isdigit() else (1, 0, part)
                               for part in version.replace('-', '.').replace('+', '.').split('.')]
    entries = sorted(texts.items(), key=lambda item: (item[0][0], min(map(key, item[1])), item[0][2]))
    numbers = {}
    for number, (_, users) in enumerate(entries, 1):
        for name in users:
            numbers.setdefault(name, []).append(number)
    lines = ['Third-party Rust crates in Illustash', '=' * 36, '',
             'The Illustash programs (illustash-terms, illustash-worker, illustash-iqdb and illustash-desktop) are built',
             'from the Rust crates listed below. Each crate is listed with the license expression it declares and the',
             'numbers of the license texts that apply to it; where a crate offers a choice of licenses, Illustash uses',
             'it under the license whose text is reproduced. Texts come from the files in each published crate; a crate',
             'that ships no license file gets the standard SPDX text. The list covers every crate the three workspaces',
             '(native/terms, desktop, crates/iqdb) can build on any platform, including build-time and test-only crates.',
             '',
             f'Generated by tools/gen_rust_licenses.py with {CARGO_ABOUT}; do not edit.', '',
             'Crates', '------', '']
    for name in sorted(numbers, key=key):
        lines.append(f"{name} ({declared[name]}): " + ', '.join(f'[{n}]' for n in numbers[name]))
    lines += ['', 'License texts', '-------------']
    for number, ((identifier, title, text), users) in enumerate(entries, 1):
        lines += ['', '-' * 78, f'[{number}] {title} ({identifier})',
                  *textwrap.wrap('Used by: ' + ', '.join(sorted(users, key=key)), 100, break_on_hyphens=False),
                  '-' * 78, '', text.rstrip('\n')]
    text = '\n'.join(lines) + '\n'
    (OUT / 'rust-dependencies.txt').write_text(text, encoding='utf-8', newline='')
    registry = {'format': 1, 'generator': CARGO_ABOUT, 'text_sha256': hashlib.sha256(text.encode()).hexdigest(),
                'workspaces': workspaces}
    (OUT / 'crates.json').write_text(json.dumps(registry, indent=2, ensure_ascii=False) + '\n', encoding='utf-8', newline='')
    build.rust_licenses()
    print(f'{len(numbers)} crates, {len(entries)} license texts, {len(text.encode())} bytes')


if __name__ == '__main__':
    main()
